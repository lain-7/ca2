# ---------------------------------------------------------------------------
# Tree manipulation helpers
# ---------------------------------------------------------------------------

def index_tree(node, path="/"):
    """Walk the whole tree and return a {absolute path: node} mapping."""
    out = {path: node}
    if node[A_TYPE] == T_DIR and isinstance(node[A_CONTENTS], list):
        for child in node[A_CONTENTS]:
            child_path = path.rstrip("/") + "/" + child[A_NAME]
            out.update(index_tree(child, child_path))
    return out


def find_parent(tree, path):
    """Return (parent node, last path component). Returns (None, None) if the path does not exist."""
    parts = [p for p in path.split("/") if p]
    if not parts:
        return None, None
    node = tree
    for part in parts[:-1]:
        if node[A_TYPE] != T_DIR or not isinstance(node[A_CONTENTS], list):
            return None, None
        nxt = next((c for c in node[A_CONTENTS] if c[A_NAME] == part), None)
        if nxt is None:
            return None, None
        node = nxt
    return node, parts[-1]


def remove_path(tree, path):
    """Remove a path. Returns whether anything was actually removed."""
    parent, name = find_parent(tree, path)
    if parent is None:
        return False
    before = len(parent[A_CONTENTS])
    parent[A_CONTENTS] = [c for c in parent[A_CONTENTS] if c[A_NAME] != name]
    return len(parent[A_CONTENTS]) < before


def ensure_dir(tree, path, mode=0o40755, uid=0, gid=0):
    """Make sure a directory exists (create if missing, keep if present)."""
    if path in index_tree(tree):
        return
    parent, name = find_parent(tree, path)
    if parent is None:
        raise RuntimeError(f"Parent directory missing, cannot create: {path}")
    parent[A_CONTENTS].append(
        [name, T_DIR, uid, gid, 4096, mode, int(time.time()), [], None, None]
    )
    parent[A_CONTENTS].sort(key=lambda c: c[A_NAME])


def ensure_file(tree, path, content: bytes, mode=0o100644,
                uid=0, gid=0, ctime=None):
    """Make sure the path is a regular file with the given content (replaced entirely if it exists)."""
    parent, name = find_parent(tree, path)
    if parent is None:
        raise RuntimeError(f"Parent directory missing, cannot write: {path}")

    # First remove any entry with the same name (may be a directory or an empty placeholder)
    remove_path(tree, path)

    node = [
        name, T_FILE, uid, gid, len(content), mode,
        int(ctime if ctime is not None else time.time()),
        content, None, None,
    ]
    parent[A_CONTENTS].append(node)
    parent[A_CONTENTS].sort(key=lambda c: c[A_NAME])
    return node


# ---------------------------------------------------------------------------
# Main flow
# ---------------------------------------------------------------------------

def main() -> int:
    if len(sys.argv) != 3:
        sys.stderr.write("Usage: rebuild_fs.py <source fs.pickle> <output fs.pickle>\n")
        return 2

    src, dst = sys.argv[1], sys.argv[2]

    with open(src, "rb") as fh:
        tree = pickle.load(fh)

    actions: list[str] = []

    # ---- 1) /etc/os-release and other distribution identifiers ----
    # Original state: the type flag for this path in the pickle was wrong; cat could not read it,
    #                 yet ls showed a 267-byte regular file.
    ensure_file(tree, "/etc/os-release", OS_RELEASE, ctime=BASE_MTIME)
    ensure_file(tree, "/etc/lsb-release", LSB_RELEASE, ctime=BASE_MTIME)
    ensure_file(tree, "/etc/debian_version",
                (DEBIAN_VER + "\n").encode(), ctime=BASE_MTIME)
    actions.append("Fixed /etc/os-release (now a non-empty regular file, 267+ bytes)")
    actions.append("Added /etc/lsb-release, /etc/debian_version")

    # ---- 2) Unify hostname ----
    ensure_file(tree, "/etc/hostname", (HOSTNAME + "\n").encode(), ctime=BASE_MTIME)
    ensure_file(tree, "/etc/hosts",
                HOSTS.format(host=HOSTNAME).encode(), ctime=BASE_MTIME)
    ensure_file(tree, "/etc/motd",
                MOTD_TEMPLATE.format(host=HOSTNAME, kernel=KERNEL,
                                     build=BUILD_STRING).encode(),
                ctime=BASE_MTIME)
    ensure_file(tree, "/etc/resolv.conf", RESOLV_CONF.encode(), ctime=BASE_MTIME)
    actions.append(f"Unified /etc/hostname, /etc/hosts, /etc/motd = {HOSTNAME}")

    # ---- 3) User database ----
    ensure_file(tree, "/etc/passwd", PASSWD, ctime=BASE_MTIME)
    ensure_file(tree, "/etc/group", GROUP, ctime=BASE_MTIME)
    # Create deploy's home directory so the /etc/passwd entry has a real counterpart
    ensure_dir(tree, "/home/deploy", mode=0o40750, uid=1000, gid=1000)
    actions.append("Replaced /etc/passwd and /etc/group (removed phil / vboxsf)")
    actions.append("Added /home/deploy home directory")

    # ---- 4) sshd_config ----
    # Original state: the file exists but is empty, while the system is running an SSH service.
    ensure_dir(tree, "/etc/ssh")
    ensure_file(tree, "/etc/ssh/sshd_config", SSHD_CONFIG, ctime=BASE_MTIME)
    actions.append("Filled /etc/ssh/sshd_config (Debian 12 default config)")

    # ---- 5) Remove container traces ----
    # Original state: this filesystem is a snapshot taken from a Docker container,
    #                 which brought /.dockerenv, /proc/docker and /var/log/runit along.
    container_markers = ["/.dockerenv", "/.dockerinit", "/proc/docker"]
    for path in container_markers:
        if remove_path(tree, path):
            actions.append(f"Removed container marker {path}")

    removed_runit = 0
    for path in list(index_tree(tree)):
        if "/runit" in path:
            if remove_path(tree, path):
                removed_runit += 1
    if removed_runit:
        actions.append(f"Removed {removed_runit} runit-related paths")

    # ---- 6) Scatter root directory timestamps ----
    # Original state: 22 entries had only 4 distinct mtimes, a uniqueness rate of 18%.
    #                 On a real system, the mtimes of directories under / span several years.
    rng = random.Random(42)  # fixed seed -> reproducible result
    span = MTIME_SPREAD_DAYS * 86400
    for child in tree[A_CONTENTS]:
        child[A_CTIME] = BASE_MTIME + rng.randint(0, span)
    actions.append(
        f"Scattered mtimes of {len(tree[A_CONTENTS])} root directory entries"
        f" (random within {MTIME_SPREAD_DAYS} days, fixed seed)"
    )

    # ---- Write back ----
    with open(dst, "wb") as fh:
        pickle.dump(tree, fh)

    print("\n".join(f"  - {a}" for a in actions))
    print(f"\nTotal nodes: {len(index_tree(tree))}")
    print(f"Output file: {dst}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
